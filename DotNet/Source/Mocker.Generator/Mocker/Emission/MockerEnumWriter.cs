using Microsoft.CodeAnalysis;
using reromanlee.Mocker.Generator.Common;
using System;
using System.Collections.Generic;
using System.Collections.Immutable;

namespace reromanlee.Mocker.Generator.Mocker
{
    /// <summary>
    /// Emits one selection enum per valid component owned by the root assembly.
    /// </summary>
    internal static class MockerEnumWriter
    {
        private const string NameSuffix = "Implementor";

        public const string NoneMember = "None";

        public static void Write(
            SourceProductionContext context,
            ImmutableArray<MockerTarget> all,
            MockerTree tree,
            MockerImports imports,
            HashSet<string> invalidTargets)
        {
            foreach (MockerTarget component in all)
            {
                if (component.Role != MockerRole.Component || invalidTargets.Contains(component.Type.FullName))
                {
                    continue;
                }

                string path;
                string rootFullName;

                if (tree.Resolve(component, out path, out rootFullName) != MockerStatus.Resolved)
                {
                    continue;
                }

                if (invalidTargets.Contains(rootFullName) || !imports.Owns(rootFullName))
                {
                    continue;
                }

                context.AddScript(
                    component.Type.FullName + "." + NameSuffix,
                    BuildScript(component, GetImplementorNames(component, all, invalidTargets)));
            }
        }

        private static List<string> GetImplementorNames(
            MockerTarget component,
            ImmutableArray<MockerTarget> all,
            HashSet<string> invalidTargets)
        {
            List<string> names = new List<string>();

            foreach (MockerTarget target in all)
            {
                if (target.Role == MockerRole.Implementor
                    && !invalidTargets.Contains(target.Type.FullName)
                    && string.Equals(target.ParentFullName, component.Type.FullName, StringComparison.Ordinal))
                {
                    names.Add(target.Name);
                }
            }

            names.Sort(StringComparer.Ordinal);

            return names;
        }

        private static string BuildScript(MockerTarget component, List<string> implementorNames)
        {
            ScriptEmitter emitter = new ScriptEmitter();
            string stem = ScriptNames.GetComponentStem(component.Type.Name, component.IsInterface);

            emitter.Line("// <auto-generated />");
            emitter.Line("#nullable disable");

            using (emitter.Namespace(component.Type.Namespace))
            {
                emitter.Line($"/// <summary>Which implementation of {component.Type.Name} to build.</summary>");

                using (emitter.Block($"public enum {stem}{NameSuffix}"))
                {
                    emitter.Line("/// <summary>Use the generated mock, which does nothing and gets in nobody's way.</summary>");
                    emitter.Line($"{NoneMember} = 0{(implementorNames.Count == 0 ? string.Empty : ",")}");

                    for (int index = 0; index < implementorNames.Count; index++)
                    {
                        bool isLast = index == implementorNames.Count - 1;
                        emitter.Line($"{implementorNames[index]}{(isLast ? string.Empty : ",")}");
                    }
                }
            }

            return emitter.ToString();
        }
    }
}
