using Microsoft.CodeAnalysis;
using reromanlee.Mocker.Generator.Common;
using System;
using System.Collections.Generic;
using System.Collections.Immutable;

namespace reromanlee.Mocker.Generator.Mocker
{
    /// <summary>
    /// Emits the composite factory and runnable composite subclass with rollback-safe construction,
    /// overlapped fault-safe asynchronous initialization, prompt temporary reference release, and
    /// atomic idempotent reverse-order disposal.
    /// </summary>
    internal static class MockerWiringWriter
    {
        private const string Task = "global::System.Threading.Tasks.Task";
        private const string Token = "global::System.Threading.CancellationToken";
        private const string TokenSource = "global::System.Threading.CancellationTokenSource";
        private const string Disposable = "global::System.IDisposable";
        private const string DisposableList = "global::System.Collections.Generic.List<global::System.IDisposable>";
        private const string ExceptionType = "global::System.Exception";
        private const string ExceptionList = "global::System.Collections.Generic.List<global::System.Exception>";
        private const string StringList = "global::System.Collections.Generic.List<string>";
        private const string InterlockedType = "global::System.Threading.Interlocked";
        private const string VolatileType = "global::System.Threading.Volatile";
        private const string ExceptionDispatchInfoType = "global::System.Runtime.ExceptionServices.ExceptionDispatchInfo";

        public static void Write(SourceProductionContext context, MockerScope scope, ImmutableArray<MockerTarget> all)
        {
            ScriptEmitter emitter = new ScriptEmitter();

            emitter.Line("// <auto-generated />");

            using (emitter.Namespace(scope.Composite.Type.Namespace))
            {
                WriteFactory(context, emitter, scope, all);
                emitter.Line();
                WriteComposite(emitter, scope);
            }

            context.AddScript(scope.Composite.Type.FullName + ".Wiring", emitter.ToString());
        }

        private static string FactoryName(MockerScope scope)
        {
            return scope.Composite.Type.Name + "Factory";
        }

        private static string ChoicesName(MockerScope scope)
        {
            string name = scope.GetChoicesTypeName(scope.Composite);

            return scope.Composite.Type.HasNamespace
                ? ScriptNames.Qualified(scope.Composite.Type.Namespace + "." + name)
                : ScriptNames.Qualified(name);
        }

        private static void WriteFactory(SourceProductionContext context, ScriptEmitter emitter, MockerScope scope, ImmutableArray<MockerTarget> all)
        {
            List<MockerTarget> rootChildren = GetValidRootChildren(scope);

            using (emitter.Block($"internal sealed class {FactoryName(scope)}"))
            {
                emitter.Line($"private readonly {ChoicesName(scope)} _choices;");
                emitter.Line($"private readonly {DisposableList} _disposables = new {DisposableList}();");
                emitter.Line("private global::reromanlee.Mocker.Dependencies _dependencies;");
                emitter.Line($"private {StringList} _resolving = new {StringList}();");
                emitter.Line();

                foreach (MockerTarget node in scope.Branches)
                {
                    if (node.Role == MockerRole.Node)
                    {
                        emitter.Line($"private {ScriptNames.Qualified(node.Type.FullName)} {scope.GetFieldId(node)};");
                    }
                }

                foreach (MockerTarget component in scope.Components)
                {
                    emitter.Line($"private {ScriptNames.Qualified(component.Type.FullName)} {scope.GetFieldId(component)};");

                    if (scope.NeedsInitialization(component))
                    {
                        emitter.Line($"private {Task} _init{scope.GetFieldId(component)};");
                    }
                }

                emitter.Line();

                using (emitter.Block($"public {FactoryName(scope)}({ChoicesName(scope)} choices, global::reromanlee.Mocker.Dependencies dependencies)"))
                {
                    emitter.Line($"_choices = choices ?? new {ChoicesName(scope)}();");
                    emitter.Line("_dependencies = dependencies ?? new global::reromanlee.Mocker.Dependencies();");
                }

                emitter.Line();

                using (emitter.Block($"public {ChoicesName(scope)} Choices"))
                {
                    emitter.Line("get { return _choices; }");
                }

                emitter.Line();
                emitter.Line("/// <summary>Builds every root branch eagerly so construction failures can roll back before base initialization.</summary>");

                using (emitter.Block("public void CreateAll()"))
                {
                    foreach (MockerTarget child in rootChildren)
                    {
                        emitter.Line($"Create{scope.GetMemberId(child)}();");
                    }
                }

                emitter.Line();
                emitter.Line("/// <summary>Releases construction-only state immediately after the object graph is built.</summary>");

                using (emitter.Block("public void CompleteConstruction()"))
                {
                    emitter.Line("_dependencies = null;");
                    emitter.Line("_resolving = null;");
                }

                foreach (MockerTarget node in scope.Branches)
                {
                    if (node.Role == MockerRole.Node)
                    {
                        WriteNodeFactory(emitter, scope, node);
                    }
                }

                foreach (MockerTarget component in scope.Components)
                {
                    WriteComponentFactory(context, emitter, scope, component, all);
                    WriteComponentInitializer(emitter, scope, component);
                }

                WriteDisposeCreated(emitter);
                WriteReleaseInitialization(emitter, scope);
                WriteRelease(emitter, scope);
                WriteResolveGuards(emitter);
            }
        }

        private static List<MockerTarget> GetValidRootChildren(MockerScope scope)
        {
            List<MockerTarget> valid = new List<MockerTarget>();

            foreach (MockerTarget child in scope.Tree.GetChildren(scope.Composite))
            {
                if (scope.GetPath(child).Length != 0)
                {
                    valid.Add(child);
                }
            }

            return valid;
        }

        private static void WriteNodeFactory(ScriptEmitter emitter, MockerScope scope, MockerTarget node)
        {
            string field = scope.GetFieldId(node);
            List<string> arguments = new List<string>();

            foreach (MockerTarget child in scope.Tree.GetChildren(node))
            {
                if (scope.GetPath(child).Length != 0)
                {
                    arguments.Add($"Create{scope.GetMemberId(child)}()");
                }
            }

            emitter.Line();

            using (emitter.Block($"public {ScriptNames.Qualified(node.Type.FullName)} Create{scope.GetMemberId(node)}()"))
            {
                using (emitter.Block($"if ({field} != null)"))
                {
                    emitter.Line($"return {field};");
                }

                emitter.Line();
                emitter.Line($"{field} = new {ScriptNames.Qualified(node.Type.FullName)}({string.Join(", ", arguments)});");
                emitter.Line($"TrackDisposable({field});");
                emitter.Line();
                emitter.Line($"return {field};");
            }
        }

        private static void WriteComponentFactory(
            SourceProductionContext context,
            ScriptEmitter emitter,
            MockerScope scope,
            MockerTarget component,
            ImmutableArray<MockerTarget> all)
        {
            string field = scope.GetFieldId(component);

            emitter.Line();

            using (emitter.Block($"public {ScriptNames.Qualified(component.Type.FullName)} Create{scope.GetMemberId(component)}()"))
            {
                using (emitter.Block($"if ({field} != null)"))
                {
                    emitter.Line($"return {field};");
                }

                emitter.Line();
                emitter.Line($"BeginResolve(\"{ScriptWriter.EscapeLiteral(scope.GetPath(component))}\");");
                emitter.Line();

                using (emitter.Block("try"))
                {
                    using (emitter.Block($"switch ({scope.GetChoicesAccessor(component)})"))
                    {
                        foreach (MockerTarget implementor in scope.GetImplementors(component))
                        {
                            emitter.Line($"case {scope.GetEnumType(component)}.{implementor.Name}:");
                            emitter.Line($"    {field} = new {ScriptNames.Qualified(implementor.Type.FullName)}({BuildArguments(context, scope, component, implementor, all)});");
                            emitter.Line("    break;");
                            emitter.Line();
                        }

                        emitter.Line("default:");
                        emitter.Line($"    {field} = new {scope.GetMockType(component)}();");
                        emitter.Line("    break;");
                    }
                }

                using (emitter.Block("finally"))
                {
                    emitter.Line("EndResolve();");
                }

                emitter.Line();
                emitter.Line($"TrackDisposable({field});");
                emitter.Line();
                emitter.Line($"return {field};");
            }
        }

        private static string BuildArguments(
            SourceProductionContext context,
            MockerScope scope,
            MockerTarget component,
            MockerTarget implementor,
            ImmutableArray<MockerTarget> all)
        {
            List<string> arguments = new List<string>();

            foreach (string parameterType in implementor.Details.ParameterTypes)
            {
                MockerTarget dependency;

                if (scope.TryGetComponent(parameterType, out dependency))
                {
                    arguments.Add($"Create{scope.GetMemberId(dependency)}()");
                    continue;
                }

                ReportForeignComponent(context, scope, implementor, parameterType, all);

                arguments.Add($"_dependencies.Require<{parameterType}>(\"{ScriptWriter.EscapeLiteral(scope.GetPath(component))}\", \"{ScriptWriter.EscapeLiteral(implementor.Type.Name)}\")");
            }

            return string.Join(", ", arguments);
        }

        private static void ReportForeignComponent(
            SourceProductionContext context,
            MockerScope scope,
            MockerTarget implementor,
            string parameterType,
            ImmutableArray<MockerTarget> all)
        {
            foreach (MockerTarget candidate in all)
            {
                if (candidate.Role != MockerRole.Component)
                {
                    continue;
                }

                if (!string.Equals(ScriptNames.Qualified(candidate.Type.FullName), parameterType, StringComparison.Ordinal))
                {
                    continue;
                }

                string owner;
                string path;

                if (scope.Tree.Resolve(candidate, out path, out owner) == MockerStatus.Resolved)
                {
                    context.Report(MockerDiagnostics.ForeignComponent, implementor.Location, implementor.Type.Name, candidate.Type.Name, owner);
                }

                return;
            }
        }

        private static void WriteComponentInitializer(ScriptEmitter emitter, MockerScope scope, MockerTarget component)
        {
            string member = scope.GetMemberId(component);
            string field = scope.GetFieldId(component);

            emitter.Line();

            if (!scope.NeedsInitialization(component))
            {
                emitter.Line("/// <summary>Nothing under this component initializes asynchronously.</summary>");

                using (emitter.Block($"public {Task} Initialize{member}Async({Token} cancellationToken)"))
                {
                    emitter.Line($"return {Task}.CompletedTask;");
                }

                return;
            }

            using (emitter.Block($"public {Task} Initialize{member}Async({Token} cancellationToken)"))
            {
                using (emitter.Block($"if (_init{field} == null)"))
                {
                    emitter.Line($"_init{field} = Run{member}Async(cancellationToken);");
                }

                emitter.Line();
                emitter.Line($"return _init{field};");
            }

            emitter.Line();

            using (emitter.Block($"private async {Task} Run{member}Async({Token} cancellationToken)"))
            {
                using (emitter.Block($"switch ({scope.GetChoicesAccessor(component)})"))
                {
                    foreach (MockerTarget implementor in scope.GetImplementors(component))
                    {
                        List<MockerTarget> asyncDependencies = new List<MockerTarget>();

                        foreach (string parameterType in implementor.Details.ParameterTypes)
                        {
                            MockerTarget dependency;

                            if (scope.TryGetComponent(parameterType, out dependency) && scope.NeedsInitialization(dependency))
                            {
                                asyncDependencies.Add(dependency);
                            }
                        }

                        emitter.Line($"case {scope.GetEnumType(component)}.{implementor.Name}:");

                        if (asyncDependencies.Count == 1)
                        {
                            emitter.Line($"    await Initialize{scope.GetMemberId(asyncDependencies[0])}Async(cancellationToken);");
                        }
                        else if (asyncDependencies.Count > 1)
                        {
                            emitter.Line("    {");

                            for (int index = 0; index < asyncDependencies.Count; index++)
                            {
                                emitter.Line($"        {Task} dependency{index} = Initialize{scope.GetMemberId(asyncDependencies[index])}Async(cancellationToken);");
                            }

                            for (int index = 0; index < asyncDependencies.Count; index++)
                            {
                                emitter.Line($"        await dependency{index};");
                            }

                            emitter.Line("    }");
                        }

                        if (implementor.Details.IsAsyncInitializable)
                        {
                            emitter.Line($"    await (({ScriptNames.Qualified(implementor.Type.FullName)}){field}).InitializeAsync(cancellationToken);");
                        }

                        emitter.Line("    break;");
                        emitter.Line();
                    }

                    emitter.Line("default:");
                    emitter.Line("    break;");
                }
            }
        }

        private static void WriteDisposeCreated(ScriptEmitter emitter)
        {
            emitter.Line();

            using (emitter.Block("private void TrackDisposable(object instance)"))
            {
                emitter.Line($"{Disposable} disposable = instance as {Disposable};");
                emitter.Line();

                using (emitter.Block("if (disposable != null)"))
                {
                    emitter.Line("_disposables.Add(disposable);");
                }
            }

            emitter.Line();
            emitter.Line("/// <summary>Disposes every tracked disposable in reverse creation order and returns any failures.</summary>");

            using (emitter.Block($"public {ExceptionList} DisposeCreated()"))
            {
                emitter.Line($"{ExceptionList} failures = null;");
                emitter.Line();

                using (emitter.Block("for (int index = _disposables.Count - 1; index >= 0; index--)"))
                {
                    using (emitter.Block("try"))
                    {
                        emitter.Line("_disposables[index].Dispose();");
                    }

                    using (emitter.Block($"catch ({ExceptionType} exception)"))
                    {
                        using (emitter.Block("if (failures == null)"))
                        {
                            emitter.Line($"failures = new {ExceptionList}();");
                        }

                        emitter.Line();
                        emitter.Line("failures.Add(exception);");
                    }
                }

                emitter.Line();
                emitter.Line("_disposables.Clear();");
                emitter.Line();
                emitter.Line("return failures;");
            }
        }

        private static void WriteReleaseInitialization(ScriptEmitter emitter, MockerScope scope)
        {
            emitter.Line();
            emitter.Line("/// <summary>Clears cached initialization tasks once InitializeAsync exits so state machines are not pinned.</summary>");

            using (emitter.Block("public void ReleaseInitialization()"))
            {
                foreach (MockerTarget component in scope.Components)
                {
                    if (scope.NeedsInitialization(component))
                    {
                        emitter.Line($"_init{scope.GetFieldId(component)} = null;");
                    }
                }
            }
        }

        private static void WriteRelease(ScriptEmitter emitter, MockerScope scope)
        {
            emitter.Line();
            emitter.Line("/// <summary>Releases every object reference retained by the factory.</summary>");

            using (emitter.Block("public void Release()"))
            {
                emitter.Line("_dependencies = null;");
                emitter.Line("_resolving = null;");
                emitter.Line("_disposables.Clear();");

                foreach (MockerTarget node in scope.Branches)
                {
                    if (node.Role == MockerRole.Node)
                    {
                        emitter.Line($"{scope.GetFieldId(node)} = null;");
                    }
                }

                foreach (MockerTarget component in scope.Components)
                {
                    emitter.Line($"{scope.GetFieldId(component)} = null;");

                    if (scope.NeedsInitialization(component))
                    {
                        emitter.Line($"_init{scope.GetFieldId(component)} = null;");
                    }
                }
            }
        }

        private static void WriteResolveGuards(ScriptEmitter emitter)
        {
            emitter.Line();

            using (emitter.Block("private void BeginResolve(string path)"))
            {
                using (emitter.Block("if (_resolving.Contains(path))"))
                {
                    emitter.Line("_resolving.Add(path);");
                    emitter.Line("throw new global::System.InvalidOperationException(\"Cycle: \" + string.Join(\" -> \", _resolving.ToArray()) + \". One of these has to stop taking the other in its constructor.\");");
                }

                emitter.Line();
                emitter.Line("_resolving.Add(path);");
            }

            emitter.Line();

            using (emitter.Block("private void EndResolve()"))
            {
                using (emitter.Block("if (_resolving != null && _resolving.Count > 0)"))
                {
                    emitter.Line("_resolving.RemoveAt(_resolving.Count - 1);");
                }
            }
        }

        private static void WriteComposite(ScriptEmitter emitter, MockerScope scope)
        {
            string composite = scope.Composite.Type.Name;
            string escapedComposite = ScriptWriter.EscapeLiteral(composite);
            string factory = FactoryName(scope);
            string choices = ChoicesName(scope);
            List<MockerTarget> rootChildren = GetValidRootChildren(scope);
            List<string> baseArguments = new List<string>(rootChildren.Count);

            foreach (MockerTarget child in rootChildren)
            {
                baseArguments.Add($"factory.Create{scope.GetMemberId(child)}()");
            }

            emitter.Line($"/// <summary>{composite} with the implementors visible to this composition root.</summary>");

            using (emitter.Block($"public class {composite}Composite : {ScriptNames.Qualified(scope.Composite.Type.FullName)}"))
            {
                emitter.Line("private const int StateNotInitialized = 0;");
                emitter.Line("private const int StateInitializing = 1;");
                emitter.Line("private const int StateInitialized = 2;");
                emitter.Line("private const int StateFailed = 3;");
                emitter.Line("private const int StateDisposed = 4;");
                emitter.Line();
                emitter.Line($"private readonly {factory} _factory;");
                emitter.Line($"private readonly {choices} _choices;");
                emitter.Line($"private readonly {TokenSource} _cancellation;");
                emitter.Line("private int _state;");
                emitter.Line();

                using (emitter.Block($"public {composite}Composite({choices} choices = null, global::reromanlee.Mocker.Dependencies dependencies = null)",
                    ": this(BuildFactory(choices, dependencies))"))
                {
                }

                emitter.Line();

                using (emitter.Block($"private static {factory} BuildFactory({choices} choices, global::reromanlee.Mocker.Dependencies dependencies)"))
                {
                    emitter.Line($"{factory} factory = new {factory}(choices, dependencies);");
                    emitter.Line();

                    using (emitter.Block("try"))
                    {
                        emitter.Line("factory.CreateAll();");
                        emitter.Line("factory.CompleteConstruction();");
                        emitter.Line("return factory;");
                    }

                    using (emitter.Block("catch"))
                    {
                        emitter.Line("factory.DisposeCreated();");
                        emitter.Line("factory.Release();");
                        emitter.Line("throw;");
                    }
                }

                emitter.Line();

                using (emitter.Block($"private {composite}Composite({factory} factory)",
                    $": base({string.Join(", ", baseArguments)})"))
                {
                    emitter.Line("_factory = factory;");
                    emitter.Line("_choices = factory.Choices;");
                    emitter.Line($"_cancellation = new {TokenSource}();");
                }

                emitter.Line();
                emitter.Line("/// <summary>The choices this composite was constructed with.</summary>");

                using (emitter.Block($"public {choices} Choices"))
                {
                    emitter.Line("get { return _choices; }");
                }

                WriteInitialize(emitter, scope, escapedComposite);
                WriteDispose(emitter, escapedComposite);
                WriteFailureHelper(emitter);
            }
        }

        private static void WriteInitialize(ScriptEmitter emitter, MockerScope scope, string escapedComposite)
        {
            List<MockerTarget> initializable = new List<MockerTarget>();

            foreach (MockerTarget component in scope.Components)
            {
                if (scope.NeedsInitialization(component))
                {
                    initializable.Add(component);
                }
            }

            emitter.Line();

            using (emitter.Block($"public override async {Task} InitializeAsync({Token} cancellationToken = default({Token}))"))
            {
                emitter.Line($"int previousState = {InterlockedType}.CompareExchange(ref _state, StateInitializing, StateNotInitialized);");
                emitter.Line();

                using (emitter.Block("if (previousState == StateDisposed)"))
                {
                    emitter.Line($"throw new global::System.ObjectDisposedException(\"{escapedComposite}\");");
                }

                emitter.Line();

                using (emitter.Block("if (previousState != StateNotInitialized)"))
                {
                    emitter.Line($"throw new global::System.InvalidOperationException(\"{escapedComposite} was already initialized.\");");
                }

                emitter.Line();
                emitter.Line($"{TokenSource} linked;");
                emitter.Line();

                using (emitter.Block("try"))
                {
                    emitter.Line($"linked = {TokenSource}.CreateLinkedTokenSource(cancellationToken, _cancellation.Token);");
                }

                using (emitter.Block("catch (global::System.ObjectDisposedException)"))
                {
                    emitter.Line($"throw new global::System.ObjectDisposedException(\"{escapedComposite}\");");
                }

                emitter.Line();

                using (emitter.Block("try"))
                {
                    emitter.Line("await OnBeforeInitialize(linked.Token);");

                    if (initializable.Count > 0)
                    {
                        emitter.Line();
                        emitter.Line($"{ExceptionList} failures = null;");
                        emitter.Line("bool hasNonCancellationFailure = false;");

                        for (int index = 0; index < initializable.Count; index++)
                        {
                            emitter.Line($"{Task} start{index} = null;");
                        }

                        emitter.Line();

                        for (int index = 0; index < initializable.Count; index++)
                        {
                            string memberId = scope.GetMemberId(initializable[index]);

                            using (emitter.Block("try"))
                            {
                                emitter.Line($"start{index} = _factory.Initialize{memberId}Async(linked.Token);");
                            }

                            using (emitter.Block($"catch ({ExceptionType} exception)"))
                            {
                                emitter.Line("failures = RecordInitializationFailure(failures, exception, ref hasNonCancellationFailure, linked);");
                            }
                        }

                        emitter.Line();

                        for (int index = 0; index < initializable.Count; index++)
                        {
                            using (emitter.Block($"if (start{index} != null)"))
                            {
                                using (emitter.Block("try"))
                                {
                                    emitter.Line($"await start{index};");
                                }

                                using (emitter.Block($"catch ({ExceptionType} exception)"))
                                {
                                    emitter.Line("failures = RecordInitializationFailure(failures, exception, ref hasNonCancellationFailure, linked);");
                                }
                            }
                        }

                        emitter.Line();

                        using (emitter.Block("if (failures != null)"))
                        {
                            emitter.Line($"ThrowInitializationFailures(\"{escapedComposite}\", failures);");
                        }
                    }

                    emitter.Line();

                    using (emitter.Block($"if ({VolatileType}.Read(ref _state) == StateDisposed)"))
                    {
                        emitter.Line($"throw new global::System.ObjectDisposedException(\"{escapedComposite}\");");
                    }

                    emitter.Line();
                    emitter.Line("await OnInitialized(linked.Token);");
                    emitter.Line($"{InterlockedType}.CompareExchange(ref _state, StateInitialized, StateInitializing);");
                }

                using (emitter.Block("catch"))
                {
                    using (emitter.Block("try"))
                    {
                        emitter.Line("linked.Cancel();");
                    }

                    using (emitter.Block("catch (global::System.ObjectDisposedException)"))
                    {
                    }

                    emitter.Line();
                    emitter.Line($"{InterlockedType}.CompareExchange(ref _state, StateFailed, StateInitializing);");
                    emitter.Line("throw;");
                }

                using (emitter.Block("finally"))
                {
                    emitter.Line("_factory.ReleaseInitialization();");
                    emitter.Line("linked.Dispose();");
                }
            }

            if (initializable.Count > 0)
            {
                emitter.Line();

                using (emitter.Block($"private static {ExceptionList} RecordInitializationFailure({ExceptionList} failures, {ExceptionType} exception, ref bool hasNonCancellationFailure, {TokenSource} linked)"))
                {
                    emitter.Line("bool isCancellation = exception is global::System.OperationCanceledException;");
                    emitter.Line();

                    using (emitter.Block("if (!isCancellation)"))
                    {
                        using (emitter.Block("if (!hasNonCancellationFailure && failures != null)"))
                        {
                            emitter.Line("failures.Clear();");
                        }

                        emitter.Line();
                        emitter.Line("hasNonCancellationFailure = true;");
                        emitter.Line("failures = AddFailure(failures, exception);");
                    }

                    using (emitter.Block("else if (!hasNonCancellationFailure)"))
                    {
                        emitter.Line("failures = AddFailure(failures, exception);");
                    }

                    emitter.Line();

                    using (emitter.Block("try"))
                    {
                        emitter.Line("linked.Cancel();");
                    }

                    using (emitter.Block("catch (global::System.ObjectDisposedException)"))
                    {
                    }

                    emitter.Line();
                    emitter.Line("return failures;");
                }

                emitter.Line();

                using (emitter.Block($"private static void ThrowInitializationFailures(string compositeName, {ExceptionList} failures)"))
                {
                    using (emitter.Block("if (failures.Count == 1)"))
                    {
                        emitter.Line($"{ExceptionDispatchInfoType}.Capture(failures[0]).Throw();");
                    }

                    emitter.Line();
                    emitter.Line("throw new global::System.AggregateException(compositeName + \" failed to initialize.\", failures);");
                }
            }
        }

        private static void WriteDispose(ScriptEmitter emitter, string escapedComposite)
        {
            emitter.Line();

            using (emitter.Block("public override void Dispose()"))
            {
                using (emitter.Block($"if ({InterlockedType}.Exchange(ref _state, StateDisposed) == StateDisposed)"))
                {
                    emitter.Line("return;");
                }

                emitter.Line();
                emitter.Line("IsDisposed = true;");
                emitter.Line($"{ExceptionList} failures = null;");
                emitter.Line();

                using (emitter.Block("try"))
                {
                    emitter.Line("_cancellation.Cancel();");
                }

                using (emitter.Block($"catch ({ExceptionType} exception)"))
                {
                    emitter.Line("failures = AddFailure(failures, exception);");
                }

                emitter.Line();

                using (emitter.Block("try"))
                {
                    emitter.Line("OnBeforeDispose();");
                }

                using (emitter.Block($"catch ({ExceptionType} exception)"))
                {
                    emitter.Line("failures = AddFailure(failures, exception);");
                }

                emitter.Line();
                emitter.Line($"{ExceptionList} disposeFailures = _factory.DisposeCreated();");
                emitter.Line();

                using (emitter.Block("if (disposeFailures != null)"))
                {
                    using (emitter.Block("if (failures == null)"))
                    {
                        emitter.Line("failures = disposeFailures;");
                    }

                    using (emitter.Block("else"))
                    {
                        emitter.Line("failures.AddRange(disposeFailures);");
                    }
                }

                emitter.Line();
                emitter.Line("_cancellation.Dispose();");
                emitter.Line("_factory.Release();");
                emitter.Line("ReleaseChildren();");
                emitter.Line();

                using (emitter.Block("try"))
                {
                    emitter.Line("OnDisposed();");
                }

                using (emitter.Block($"catch ({ExceptionType} exception)"))
                {
                    emitter.Line("failures = AddFailure(failures, exception);");
                }

                emitter.Line();

                using (emitter.Block("if (failures != null)"))
                {
                    emitter.Line($"throw new global::System.AggregateException(\"{escapedComposite} did not dispose cleanly.\", failures);");
                }
            }
        }

        private static void WriteFailureHelper(ScriptEmitter emitter)
        {
            emitter.Line();

            using (emitter.Block($"private static {ExceptionList} AddFailure({ExceptionList} failures, {ExceptionType} exception)"))
            {
                using (emitter.Block("if (failures == null)"))
                {
                    emitter.Line($"failures = new {ExceptionList}();");
                }

                emitter.Line();
                emitter.Line("failures.Add(exception);");
                emitter.Line("return failures;");
            }
        }
