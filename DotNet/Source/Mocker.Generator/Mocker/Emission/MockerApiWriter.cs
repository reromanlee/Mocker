using Microsoft.CodeAnalysis;
using reromanlee.Mocker.Generator.Common;
using System.Collections.Generic;
using System.Collections.Immutable;

namespace reromanlee.Mocker.Generator.Mocker
{
    /// <summary>
    /// Emits partial composite and node APIs: O(1) field-backed child properties, disposal guards
    /// on both composites and nodes, constructor wiring, reference release, and lifecycle hooks.
    /// </summary>
    internal static class MockerApiWriter
    {
        private const string Task = "global::System.Threading.Tasks.Task";
        private const string Token = "global::System.Threading.CancellationToken";

        public static void Write(
            SourceProductionContext context,
            ImmutableArray<MockerTarget> local,
            MockerTree tree,
            HashSet<string> invalidTargets)
        {
            foreach (MockerTarget target in local)
            {
                bool isBranch = target.Role == MockerRole.Composite || target.Role == MockerRole.Node;

                if (!isBranch || !target.IsPartial || invalidTargets.Contains(target.Type.FullName))
                {
                    continue;
                }

                List<MockerTarget> validChildren = new List<MockerTarget>();

                foreach (MockerTarget child in tree.GetChildren(target))
                {
                    if (!invalidTargets.Contains(child.Type.FullName))
                    {
                        validChildren.Add(child);
                    }
                }

                context.AddScript(target.Type.FullName + ".Api", BuildScript(target, validChildren));
            }
        }

        private static string BuildScript(MockerTarget target, List<MockerTarget> children)
        {
            ScriptEmitter emitter = new ScriptEmitter();
            bool isComposite = target.Role == MockerRole.Composite;
            string bases = isComposite ? " : global::System.IDisposable" : string.Empty;

            emitter.Line("// <auto-generated />");

            using (emitter.Namespace(target.Type.Namespace))
            using (emitter.Block($"partial class {target.Type.Name}{bases}"))
            {
                WriteFields(emitter, children, isComposite);
                WriteConstructor(emitter, target, children);
                WriteProperties(emitter, children, isComposite, target.Type.Name);
                WriteRelease(emitter, children, isComposite);

                if (isComposite)
                {
                    WriteLifecycle(emitter);
                }
            }

            return emitter.ToString();
        }

        private static void WriteFields(ScriptEmitter emitter, List<MockerTarget> children, bool isComposite)
        {
            if (!isComposite)
            {
                emitter.Line("private bool _isDisposed;");
            }

            foreach (MockerTarget child in children)
            {
                emitter.Line($"private {ScriptNames.Qualified(child.Type.FullName)} {ScriptNames.ToField(child.Name)};");
            }

            if (!isComposite || children.Count > 0)
            {
                emitter.Line();
            }
        }

        private static void WriteConstructor(ScriptEmitter emitter, MockerTarget target, List<MockerTarget> children)
        {
            List<string> parameters = new List<string>(children.Count);

            foreach (MockerTarget child in children)
            {
                parameters.Add($"{ScriptNames.Qualified(child.Type.FullName)} {ScriptNames.ToParameter(child.Name)}");
            }

            string accessibility = target.Role == MockerRole.Composite ? "protected" : "public";

            using (emitter.Block($"{accessibility} {target.Type.Name}({string.Join(", ", parameters)})"))
            {
                foreach (MockerTarget child in children)
                {
                    emitter.Line($"{ScriptNames.ToField(child.Name)} = {ScriptNames.ToParameter(child.Name)};");
                }
            }
        }

        private static void WriteProperties(ScriptEmitter emitter, List<MockerTarget> children, bool isComposite, string typeName)
        {
            string disposedCheck = isComposite ? "IsDisposed" : "_isDisposed";

            foreach (MockerTarget child in children)
            {
                emitter.Line();

                using (emitter.Block($"public {ScriptNames.Qualified(child.Type.FullName)} {ScriptNames.Escape(child.Name)}"))
                using (emitter.Block("get"))
                {
                    using (emitter.Block($"if ({disposedCheck})"))
                    {
                        emitter.Line($"throw new global::System.ObjectDisposedException(\"{ScriptWriter.EscapeLiteral(typeName)}\");");
                    }

                    emitter.Line();
                    emitter.Line($"return {ScriptNames.ToField(child.Name)};");
                }
            }
        }

        private static void WriteRelease(ScriptEmitter emitter, List<MockerTarget> children, bool isComposite)
        {
            emitter.Line();
            emitter.Line("/// <summary>Marks this branch disposed and releases child references so GC collects the subtree even while callers retain a reference.</summary>");

            using (emitter.Block($"{(isComposite ? "protected" : "internal")} void ReleaseChildren()"))
            {
                if (!isComposite)
                {
                    emitter.Line("_isDisposed = true;");
                }

                foreach (MockerTarget child in children)
                {
                    string field = ScriptNames.ToField(child.Name);

                    if (child.Role == MockerRole.Node)
                    {
                        using (emitter.Block($"if ({field} != null)"))
                        {
                            emitter.Line($"{field}.ReleaseChildren();");
                        }

                        emitter.Line();
                    }

                    emitter.Line($"{field} = null;");
                }
            }
        }

        private static void WriteLifecycle(ScriptEmitter emitter)
        {
            emitter.Line();
            emitter.Line("/// <summary>True once <see cref=\"Dispose\"/> has started tearing down this composite.</summary>");
            emitter.Line("public bool IsDisposed { get; protected set; }");
            emitter.Line();
            emitter.Line("/// <summary>Initializes every asynchronous implementor, overlapping independent branches and waiting on constructor dependencies.</summary>");
            emitter.Line($"public abstract {Task} InitializeAsync({Token} cancellationToken = default({Token}));");
            emitter.Line();
            emitter.Line("/// <summary>Disposes all created <see cref=\"global::System.IDisposable\"/> instances in reverse creation order and releases all references.</summary>");
            emitter.Line("public abstract void Dispose();");
            emitter.Line();
            emitter.Line("/// <summary>Runs before component initialization starts; derived constructor fields are assigned.</summary>");

            using (emitter.Block($"protected virtual {Task} OnBeforeInitialize({Token} cancellationToken)"))
            {
                emitter.Line($"return {Task}.CompletedTask;");
            }

            emitter.Line();
            emitter.Line("/// <summary>Runs after all component initializers complete successfully.</summary>");

            using (emitter.Block($"protected virtual {Task} OnInitialized({Token} cancellationToken)"))
            {
                emitter.Line($"return {Task}.CompletedTask;");
            }

            emitter.Line();
            emitter.Line("/// <summary>Runs before created disposables are torn down.</summary>");

            using (emitter.Block("protected virtual void OnBeforeDispose()"))
            {
            }

            emitter.Line();
            emitter.Line("/// <summary>Runs after all disposables and child references have been released.</summary>");

            using (emitter.Block("protected virtual void OnDisposed()"))
            {
            }
        }
    }
}
