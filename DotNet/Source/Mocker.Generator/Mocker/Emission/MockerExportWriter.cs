using Microsoft.CodeAnalysis;
using reromanlee.Mocker.Generator.Common;
using System;
using System.Collections.Generic;
using System.Collections.Immutable;

namespace reromanlee.Mocker.Generator.Mocker
{
    /// <summary>
    /// Publishes valid local Mocker types as assembly-level <c>[MockerExport]</c> attributes
    /// so downstream root assemblies resolve cross-assembly graphs in O(exports) time.
    /// </summary>
    internal static class MockerExportWriter
    {
        private const string ScriptName = "MockerExports";

        public static void Write(
            SourceProductionContext context,
            ImmutableArray<MockerTarget> local,
            HashSet<string> invalidTargets)
        {
            List<string> exports = new List<string>();

            foreach (MockerTarget target in local)
            {
                if (target.IsExternal || target.Type.IsEmpty || invalidTargets.Contains(target.Type.FullName))
                {
                    continue;
                }

                string parent = target.HasParent ? $"typeof({ScriptNames.Qualified(target.ParentFullName)})" : "null";

                exports.Add($"[assembly: global::reromanlee.Mocker.MockerExport(\"{target.Role}\", typeof({ScriptNames.Qualified(target.Type.FullName)}), \"{ScriptWriter.EscapeLiteral(target.Name)}\", {parent})]");
            }

            if (exports.Count == 0)
            {
                return;
            }

            exports.Sort(StringComparer.Ordinal);

            ScriptEmitter emitter = new ScriptEmitter();

            emitter.Line("// <auto-generated />");
            emitter.Line("#nullable disable");

            foreach (string export in exports)
            {
                emitter.Line(export);
            }

            context.AddScript(ScriptName, emitter.ToString());
        }
    }
}
